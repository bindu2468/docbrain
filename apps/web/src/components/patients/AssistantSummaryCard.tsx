'use client';

import { useQuery } from '@tanstack/react-query';
import { Loader2, MessageCircleQuestion, Sparkles } from 'lucide-react';
import type { MedicalSpecialty } from '@docbrain/shared';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { clinicalAssistantApi } from '@/lib/clinical-assistant-api';
import { CitedText } from './CitedText';

interface AssistantSummaryCardProps {
  organizationId: string;
  patientId: string;
  /** Undefined means the doctor's own specialty */
  specialty: MedicalSpecialty | undefined;
  onAskQuestion: (question: string) => void;
}

/**
 * The model-written 30-second brief and questions to ask today. Sits beside
 * the rule-based brief, never in place of it: allergies and flags above this
 * card are computed, not generated.
 */
export const AssistantSummaryCard = ({
  organizationId,
  patientId,
  specialty,
  onAskQuestion,
}: AssistantSummaryCardProps) => {
  const {
    data: summary,
    isLoading,
    isError,
    refetch,
  } = useQuery({
    queryKey: ['assistant-summary', organizationId, patientId, specialty ?? 'own'],
    queryFn: () => clinicalAssistantApi.getSummary(organizationId, patientId, specialty),
    // The server caches per record version; no need to refetch on focus
    staleTime: 5 * 60 * 1000,
    retry: false,
  });

  return (
    <Card className="border-primary/30">
      <CardHeader className="pb-3">
        <CardTitle className="flex items-center gap-2 text-base">
          <Sparkles className="h-4 w-4" aria-hidden="true" />
          AI summary
        </CardTitle>
        <CardDescription>
          Written by a language model from the records below. Every claim links to its source.
        </CardDescription>
      </CardHeader>

      <CardContent className="space-y-4">
        {isLoading && (
          <p className="flex items-center gap-2 text-sm text-muted-foreground" aria-live="polite">
            <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
            Reading the record…
          </p>
        )}

        {isError && (
          <div className="flex items-center gap-3 text-sm text-muted-foreground">
            The summary could not be generated.
            <Button variant="outline" size="sm" onClick={() => refetch()}>
              Try again
            </Button>
          </div>
        )}

        {summary && (
          <>
            <p className="text-sm leading-relaxed">
              <CitedText text={summary.summary} citations={summary.citations} />
            </p>

            {summary.suggestedQuestions.length > 0 && (
              <section aria-labelledby="suggested-questions-heading" className="space-y-2">
                <h3
                  id="suggested-questions-heading"
                  className="flex items-center gap-2 text-sm font-semibold"
                >
                  <MessageCircleQuestion className="h-4 w-4" aria-hidden="true" />
                  Ask the patient today
                </h3>
                <ul className="space-y-2">
                  {summary.suggestedQuestions.map((suggestion) => (
                    <li key={suggestion.question} className="rounded-md bg-muted/50 p-3 text-sm">
                      <p className="font-medium">{suggestion.question}</p>
                      {suggestion.rationale && (
                        <p className="mt-0.5 text-muted-foreground">
                          <CitedText text={suggestion.rationale} citations={summary.citations} />
                        </p>
                      )}
                      <Button
                        variant="link"
                        size="sm"
                        className="h-auto p-0 text-xs"
                        onClick={() => onAskQuestion(suggestion.question)}
                      >
                        Look into this in the record
                      </Button>
                    </li>
                  ))}
                </ul>
              </section>
            )}

            <p className="text-xs text-muted-foreground">
              Generated by {summary.model}. Check each claim against its source; the clinical
              decision is yours.
            </p>
          </>
        )}
      </CardContent>
    </Card>
  );
};
